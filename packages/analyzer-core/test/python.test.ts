import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { analyzeCommit, type AnalysisResult } from '@atlas/analyzer-core';
import { gzipDeterministic, packArtifact } from '@atlas/artifact/node';
import { gitVersion, openLocalRepository, resolveLocalCommit, type SafeGit } from '@atlas/ingest';
import { formatDiagnosticMessage, localRepositoryId, perimeterName, validateArtifactBundle, type GraphNode, type GraphSnapshot } from '@atlas/schema';
import { createGitFixture, type GitFixture } from '@atlas/test-fixtures';

/**
 * Python through the whole pipeline (ADR-060): a repository holding a TS web app and a
 * Python service, analyzed, packed and validated like any other. Every expectation below
 * is written from ADR-056 and ADR-057, not read back from the analyzer.
 */
const PYPROJECT = [
  '[project]',
  'name = "Harbor_Service"',
  'dependencies = ["requests>=2.31", "PyYAML==6.0.1", "six"]',
  '[dependency-groups]',
  'dev = ["pytest>=8"]',
  '',
].join('\n');

const APP_V1 = [
  '"""Service entry point."""',
  'import os',
  'import json as _json',
  'from typing import TYPE_CHECKING',
  '',
  'import requests',
  'import yaml',
  'import six',
  'import numpy',
  '',
  'from . import models',
  'from .models import User',
  '',
  'if TYPE_CHECKING:',
  '    from .types import Alias',
  '',
  'try:',
  '    import orjson',
  'except ImportError:',
  '    orjson = None',
  '',
  '',
  'def main(argv):',
  '    if not argv:',
  '        return 0',
  '    for a in argv:',
  '        if a == "-v" or a == "--verbose":',
  '            print(a)',
  '    return 1',
  '',
].join('\n');

const FILES: Record<string, string> = {
  'package.json': JSON.stringify({ name: 'harbor-web', private: true, dependencies: { react: '^19.0.0', six: '1.0.0' } }),
  'web/main.ts': "import { greet } from './greet';\nimport React from 'react';\nimport six from 'six';\nexport const x = greet([React, six]);\n",
  'web/greet.ts': "export function greet(v: unknown): string {\n  return v ? 'a' : 'b';\n}\n",
  'service/pyproject.toml': PYPROJECT,
  'service/src/harbor_service/__init__.py': 'from .app import main\n__all__ = ["main"]\n',
  'service/src/harbor_service/app.py': APP_V1,
  'service/src/harbor_service/models.py': 'class User:\n    def __init__(self, name):\n        self.name = name\n',
  'service/src/harbor_service/types.py': 'Alias = int\n',
  'service/src/harbor_service/broken.py': 'def f(:\n    pass\n',
  'service/src/harbor_service/api_pb2.py': '# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\nimport os\n',
  'service/tests/test_app.py': 'import pytest\nfrom harbor_service.app import main\n\n\ndef test_main():\n    assert main([]) == 0\n',
  'service/.venv/lib/site.py': 'import os\n',
  'scripts/tool.py': 'import helpers\nimport logging\n',
  'scripts/helpers.py': 'VALUE = 1\n',
  'scripts/logging.py': 'def log(x):\n    return x\n',
};

const repoId = localRepositoryId('6b1f2d3c-4a5e-4f60-8a7b-9c0d1e2f3a4b');
let fixture: GitFixture;
let git: SafeGit;
let version: string;
let result: AnalysisResult;
let graph: GraphSnapshot;
let byId: Map<string, GraphNode>;

const analyze = (commitOid: string) =>
  analyzeCommit({
    git,
    commitOid,
    gitVersion: version,
    repository: { repoId, displayName: 'harbor-mixed', sourceKind: 'local-git', remote: null, objectFormat: 'sha1' },
    now: () => new Date('2026-10-15T00:00:00.000Z'),
  });

beforeAll(async () => {
  fixture = createGitFixture([
    { date: '2026-10-01T10:00:00Z', message: 'Start the mixed repository', files: FILES },
    { date: '2026-10-02T10:00:00Z', message: 'Add a helper', files: { 'service/src/harbor_service/app.py': `${APP_V1}\n\ndef helper():\n    return [x for x in range(3) if x]\n` } },
  ]);
  const opened = await openLocalRepository(fixture.dir);
  git = opened.git;
  version = await gitVersion();
  result = await analyze(await resolveLocalCommit(opened.repo, git));
  graph = result.draft.graphs.at(-1)!;
  byId = new Map(graph.nodes.map((n) => [n.id, n]));
}, 120_000);
afterAll(async () => {
  await git?.dispose();
  fixture?.dispose();
});

const fileNode = (path: string) => graph.nodes.find((n) => n.kind === 'file' && n.path === path);
const targetKey = (id: string | null): string | null => {
  const t = id === null ? undefined : byId.get(id);
  if (!t) return null;
  if (t.kind === 'file') return t.path;
  if (t.kind === 'external-package' || t.kind === 'builtin') return perimeterName(t);
  return t.kind;
};
const observationsOf = (path: string) =>
  graph.importObservations
    .filter((o) => byId.get(o.sourceId)?.kind === 'file' && (byId.get(o.sourceId) as { path: string }).path === path)
    .map((o) => [o.kind, o.specifier, o.status, targetKey(o.targetId), o.confidence, o.reasonCode].join(' | '))
    .sort();

describe('Python in the analyzer pipeline (ADR-060)', () => {
  it('produces an artifact that passes every invariant, including derived Python node IDs', () => {
    const packed = packArtifact(result.draft, gzipDeterministic);
    const validation = validateArtifactBundle({ manifest: packed.manifest, graphs: result.draft.graphs, history: result.draft.history, layout: result.draft.layout });
    expect(validation.ok ? [] : validation.issues.slice(0, 5)).toEqual([]);
    expect(result.draft.graphs).toHaveLength(2);
    expect(packed.manifest.schemaVersion).toBe('atlas.graph/1.1.0');
    expect(packed.manifest.artifactVersion).toBe('atlas.artifact/1.4.0');
    expect(packed.manifest.analyzer.parserVersion).toMatch(/^typescript@\S+ tree-sitter-python@0\.25\.0\+atlas\.1\+wts@0\.27\.1$/);
  });

  it('classifies Python files by role and language, and excludes environments and generated code', () => {
    const files = Object.fromEntries(graph.nodes.flatMap((n) => (n.kind === 'file' ? [[n.path, `${n.role}/${n.language ?? '-'}/${n.parseStatus}`]] : [])));
    expect(files).toMatchObject({
      'service/src/harbor_service/app.py': 'source/python/parsed',
      'service/src/harbor_service/__init__.py': 'source/python/parsed',
      'service/tests/test_app.py': 'test/python/parsed',
      'service/src/harbor_service/broken.py': 'source/python/failed',
      'service/pyproject.toml': 'config/-/unsupported',
      'web/main.ts': 'source/typescript/parsed',
    });
    expect(files['service/src/harbor_service/api_pb2.py']).toBeUndefined();
    expect(files['service/.venv/lib/site.py']).toBeUndefined();
    expect(result.summary.exclusions).toEqual(expect.arrayContaining([{ reason: 'GENERATED_HEADER', count: 1 }, { reason: 'DEPENDENCY_DIRECTORY', count: 1 }]));
    expect(result.summary.excludedRoots).toEqual(expect.arrayContaining([{ path: 'service/.venv', reason: 'DEPENDENCY_DIRECTORY', files: 1 }]));
  });

  it('makes the Python project a package with its declared PyPI dependencies', () => {
    const packages = graph.nodes.flatMap((n) => (n.kind === 'package' ? [`${n.path || '<root>'}:${n.packageName}`] : [])).sort();
    expect(packages).toEqual(['<root>:harbor-web', 'service:Harbor_Service']);
    const pypi = graph.nodes.flatMap((n) => (n.kind === 'external-package' && n.ecosystem === 'pypi' ? [`${n.packageName}:${n.declaredRanges.map((r) => `${r.field}=${r.range}`).join(',')}`] : [])).sort();
    expect(pypi).toEqual(['numpy:', 'orjson:', 'pytest:devDependencies=>=8', 'pyyaml:dependencies===6.0.1', 'requests:dependencies=>=2.31', 'six:dependencies=*']);
    // npm six and PyPI six are different packages with different identities.
    const sixes = graph.nodes.filter((n) => n.kind === 'external-package' && n.packageName === 'six');
    expect(sixes.map((n) => perimeterName(n as never)).sort()).toEqual(['npm:six', 'pypi:six']);
    expect(new Set(sixes.map((n) => n.id)).size).toBe(2);
  });

  it('resolves every Python import as ADR-057 specifies', () => {
    expect(observationsOf('service/src/harbor_service/app.py')).toEqual(
      [
        'imports-value | os | builtin | builtin:python:os | exact | ',
        'imports-value | json | builtin | builtin:python:json | exact | ',
        'imports-value | typing | builtin | builtin:python:typing | exact | ',
        'imports-value | requests | resolved-external | pypi:requests | exact | ',
        'imports-value | yaml | resolved-external | pypi:pyyaml | exact | ',
        'imports-value | six | resolved-external | pypi:six | exact | ',
        'imports-value | numpy | resolved-external | pypi:numpy | inferred | UNDECLARED_EXTERNAL_IMPORT',
        // `from . import models` imports the package and, separately, its submodule.
        'imports-value | . | resolved-internal | service/src/harbor_service/__init__.py | exact | ',
        'imports-value | .models | resolved-internal | service/src/harbor_service/models.py | exact | ',
        'imports-value | .models | resolved-internal | service/src/harbor_service/models.py | exact | ',
        'imports-type | .types | resolved-internal | service/src/harbor_service/types.py | exact | ',
        'imports-value | orjson | resolved-external | pypi:orjson | inferred | OPTIONAL_EXTERNAL_IMPORT',
      ].sort(),
    );
    expect(observationsOf('service/src/harbor_service/__init__.py')).toEqual(['reexports-value | .app | resolved-internal | service/src/harbor_service/app.py | exact | ']);
    expect(observationsOf('service/tests/test_app.py')).toEqual(
      ['imports-value | pytest | resolved-external | pypi:pytest | exact | ', 'imports-value | harbor_service.app | resolved-internal | service/src/harbor_service/app.py | exact | '].sort(),
    );
    // A script's own directory is the first import root, and shadows the standard library there.
    expect(observationsOf('scripts/tool.py')).toEqual(
      ['imports-value | helpers | resolved-internal | scripts/helpers.py | exact | ', 'imports-value | logging | resolved-internal | scripts/logging.py | inferred | STDLIB_SHADOWED'].sort(),
    );
    // TS/JS in the same repository resolves exactly as before.
    expect(observationsOf('web/main.ts')).toEqual(
      ['imports-value | ./greet | resolved-internal | web/greet.ts | inferred | ', 'imports-value | react | resolved-external | npm:react | exact | ', 'imports-value | six | resolved-external | npm:six | exact | '].sort(),
    );
  });

  it('measures Python files and reports a syntax error as a finding', () => {
    const app = graph.metrics.find((m) => m.nodeId === fileNode('service/src/harbor_service/app.py')!.id)!;
    // main: 1 + if + for + if + or = 5; helper: 1 + comprehension for + comprehension if = 3.
    expect(app.maxCyclomatic).toBe(5);
    expect(app.codeLines).toBeGreaterThan(20);
    const parse = graph.diagnostics.filter((d) => d.ruleId === 'ATLAS_PARSE_ERROR');
    expect(parse.map((d) => [targetKey(d.subjectIds[0]!), d.messageCode, formatDiagnosticMessage(d)])).toEqual([
      ['service/src/harbor_service/broken.py', 'PYTHON_SYNTAX_ERROR', expect.stringMatching(/^Python syntax error at line 1\b.*; no dependency or complexity facts were extracted\.$/)],
    ]);
  });

  it('places PyPI and standard-library terminals on the city perimeter', () => {
    const anchors = result.draft.layout.externalAnchors.map((a) => a.canonicalName);
    expect(anchors).toEqual(expect.arrayContaining(['pypi:requests', 'builtin:python:os', 'npm:react', 'npm:six', 'pypi:six']));
  });

  it('is deterministic', async () => {
    const again = await analyze(graph.commitOid);
    expect(packArtifact(again.draft, gzipDeterministic).manifest.chunks.map((c) => c.sha256)).toEqual(packArtifact(result.draft, gzipDeterministic).manifest.chunks.map((c) => c.sha256));
  }, 120_000);
});

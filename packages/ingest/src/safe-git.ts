import { spawn, type ChildProcessWithoutNullStreams } from 'node:child_process';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { IngestError } from './errors.js';
import { runBounded, type BoundedRunResult } from './process.js';

export type ObjectFormat = 'sha1' | 'sha256';
/**
 * `https-github` may name an HTTP CONNECT broker (`http://host:port`, plan §8.3); Git then
 * reaches GitHub only through it. `local-fixture` fetches from a trusted local bare
 * repository over the `file` protocol only: authored demos and acquisition tests.
 */
export type NetworkPolicy =
  | { kind: 'offline' }
  | { kind: 'https-github'; remoteUrl: string; promisor: boolean; proxy?: string }
  | { kind: 'local-fixture'; remotePath: string };

const PROXY_PATTERN = /^http:\/\/[a-z0-9][a-z0-9.-]{0,252}:\d{1,5}$/;
const REMOTE_PATTERN = /^https:\/\/github\.com\/[A-Za-z0-9-]{1,39}\/[A-Za-z0-9._-]{1,100}\.git$/;

function checkedNetwork(network: NetworkPolicy): void {
  if (network.kind === 'https-github') {
    if (!REMOTE_PATTERN.test(network.remoteUrl)) throw new IngestError('INVALID_REPOSITORY_URL', 'Remote URLs are constructed from validated GitHub owner/name only');
    if (network.proxy !== undefined && !PROXY_PATTERN.test(network.proxy)) throw new IngestError('GIT_FAILED', 'Invalid egress broker address');
  }
  if (network.kind === 'local-fixture' && (!path.isAbsolute(network.remotePath) || /["\n\r\0]/.test(network.remotePath))) {
    throw new IngestError('GIT_FAILED', 'Fixture remotes must be absolute local paths');
  }
}

export interface SafeGitOptions {
  /** Trusted Git executable (resolved by the CLI/worker, never from repository data). */
  gitExecutable?: string;
  /** Object store to read. For the local adapter this is the user's validated objects dir. */
  objectDirectory: string | null;
  objectFormat: ObjectFormat;
  network: NetworkPolicy;
  /** Parent directory for ATLAS-owned scratch (defaults to the OS temp dir). */
  scratchRoot?: string;
  /**
   * Reuse this exact ATLAS scratch directory (a later acquisition stage deepening the same
   * bare repository). Configuration, HEAD and hook directories are regenerated, so nothing
   * written by an earlier process is trusted.
   */
  scratchDir?: string;
  defaultTimeoutMs?: number;
}

/**
 * Values injected with `-c` on every invocation as defense in depth. The generated config
 * file already sets them; command-line config wins over any file Git might still read.
 */
function hardeningConfig(emptyDir: string, emptyFile: string, network: NetworkPolicy): string[] {
  const pairs: [string, string][] = [
    ['core.hooksPath', emptyDir],
    ['core.fsmonitor', 'false'],
    ['core.attributesFile', emptyFile],
    ['core.askPass', ''],
    ['core.pager', 'cat'],
    ['core.sshCommand', 'false'],
    ['core.gitProxy', ''],
    ['core.alternateRefsCommand', ''],
    ['core.untrackedCache', 'false'],
    ['core.quotePath', 'false'],
    ['core.autocrlf', 'false'],
    ['core.longpaths', 'true'],
    ['credential.helper', ''],
    ['diff.external', ''],
    ['diff.noprefix', 'false'],
    ['diff.relative', 'false'],
    ['color.ui', 'false'],
    ['gc.auto', '0'],
    ['maintenance.auto', 'false'],
    ['fetch.recurseSubmodules', 'false'],
    ['submodule.recurse', 'false'],
    ['transfer.fsckObjects', 'true'],
    ['http.followRedirects', 'false'],
    // Keep fetched packs packed, so bytes on disk track transferred bytes closely.
    ['fetch.unpackLimit', '1'],
    ['transfer.unpackLimit', '1'],
    ['protocol.allow', 'never'],
  ];
  if (network.kind === 'https-github') {
    pairs.push(['protocol.https.allow', 'always'], ['http.proxy', network.proxy ?? ''], ['http.sslVerify', 'true']);
  }
  if (network.kind === 'local-fixture') pairs.push(['protocol.file.allow', 'always']);
  return pairs.flatMap(([k, v]) => ['-c', `${k}=${v}`]);
}

function generatedConfig(format: ObjectFormat, network: NetworkPolicy, emptyDir: string): string {
  const lines = [
    '# Generated by ATLAS. Repository-provided configuration is never loaded.',
    '[core]',
    `\trepositoryformatversion = ${format === 'sha256' || network.kind === 'https-github' ? 1 : 0}`,
    '\tbare = true',
    '\tfilemode = false',
    '\tlogallrefupdates = false',
    `\thooksPath = ${emptyDir.replaceAll('\\', '/')}`,
    '\tfsmonitor = false',
    '[gc]',
    '\tauto = 0',
  ];
  const extensions: string[] = [];
  if (format === 'sha256') extensions.push('\tobjectformat = sha256');
  if (network.kind === 'https-github' && network.promisor) extensions.push('\tpartialclone = origin');
  if (extensions.length > 0) lines.push('[extensions]', ...extensions);
  if (network.kind === 'https-github') {
    lines.push('[remote "origin"]', `\turl = ${network.remoteUrl}`);
    if (network.promisor) lines.push('\tpromisor = true', '\tpartialclonefilter = blob:none');
  }
  if (network.kind === 'local-fixture') lines.push('[remote "origin"]', `\turl = "${network.remotePath.replaceAll('\\', '/')}"`);
  return `${lines.join('\n')}\n`;
}

/**
 * Runs trusted Git against an ATLAS-generated metadata directory (plan §8.3, §8.4).
 *
 * - Never loads system, global or repository configuration; never runs hooks, filters,
 *   textconv, external diff, credential helpers, fsmonitor or pagers.
 * - Offline instances allow no transport protocol at all and set GIT_NO_LAZY_FETCH, so a
 *   missing object is an explicit error rather than a hidden network fetch.
 * - Arguments are arrays (no shell); object IDs are validated before use and never
 *   interpreted as revision expressions.
 */
export class SafeGit {
  private constructor(
    readonly scratch: string,
    readonly gitDir: string,
    private readonly env: Record<string, string>,
    private readonly hardening: string[],
    readonly objectFormat: ObjectFormat,
    readonly network: NetworkPolicy,
    private readonly gitExecutable: string,
    private readonly defaultTimeoutMs: number,
  ) {}

  static async create(options: SafeGitOptions): Promise<SafeGit> {
    checkedNetwork(options.network);
    const scratch = options.scratchDir ?? (await mkdtemp(path.join(options.scratchRoot ?? tmpdir(), 'atlas-git-')));
    if (options.scratchDir) {
      await mkdir(scratch, { recursive: true });
      // Regenerate everything but the object store and shallow list on reuse.
      for (const stale of ['empty', 'empty-config', 'global-config', 'home', 'tmp', 'meta.git/hooks', 'meta.git/info', 'meta.git/config', 'meta.git/objects/info/alternates', 'meta.git/objects/info/http-alternates']) {
        await rm(path.join(scratch, ...stale.split('/')), { recursive: true, force: true });
      }
    }
    const gitDir = path.join(scratch, 'meta.git');
    const emptyDir = path.join(scratch, 'empty');
    const emptyFile = path.join(scratch, 'empty-config');
    const home = path.join(scratch, 'home');
    const tmp = path.join(scratch, 'tmp');
    await Promise.all([
      mkdir(path.join(gitDir, 'objects'), { recursive: true }),
      mkdir(path.join(gitDir, 'refs', 'heads'), { recursive: true }),
      mkdir(path.join(gitDir, 'refs', 'tags'), { recursive: true }),
      mkdir(emptyDir, { recursive: true }),
      mkdir(home, { recursive: true }),
      mkdir(tmp, { recursive: true }),
    ]);
    await writeFile(emptyFile, '');
    // A trusted fixture remote may be owned by another user (a read-only container mount).
    // Git strips command-line config from a local upload-pack, so this one exception lives
    // in a generated global file naming exactly that path; nothing else is ever in it.
    const globalConfig = path.join(scratch, 'global-config');
    if (options.network.kind === 'local-fixture') {
      const remote = options.network.remotePath.replaceAll('\\', '/');
      await writeFile(globalConfig, `[safe]\n\tdirectory = ${remote}\n\tdirectory = ${remote}/.git\n`);
    }
    await writeFile(path.join(gitDir, 'HEAD'), 'ref: refs/heads/atlas\n');
    await writeFile(path.join(gitDir, 'config'), generatedConfig(options.objectFormat, options.network, emptyDir));

    const env: Record<string, string> = {
      GIT_DIR: gitDir,
      GIT_CONFIG_NOSYSTEM: '1',
      GIT_CONFIG_SYSTEM: emptyFile,
      GIT_CONFIG_GLOBAL: options.network.kind === 'local-fixture' ? globalConfig : emptyFile,
      GIT_ATTR_NOSYSTEM: '1',
      GIT_NO_REPLACE_OBJECTS: '1',
      GIT_TERMINAL_PROMPT: '0',
      GIT_OPTIONAL_LOCKS: '0',
      GIT_ADVICE: '0',
      GIT_PROTOCOL_FROM_USER: '0',
      GIT_ALLOW_PROTOCOL: options.network.kind === 'offline' ? '' : options.network.kind === 'local-fixture' ? 'file' : 'https',
      GIT_NO_LAZY_FETCH: '1',
      HOME: home,
      XDG_CONFIG_HOME: home,
      TMPDIR: tmp,
      TMP: tmp,
      TEMP: tmp,
      LANG: 'C',
      LC_ALL: 'C',
    };
    if (options.objectDirectory) env['GIT_OBJECT_DIRECTORY'] = options.objectDirectory;
    // Windows needs a few system variables for process startup, sockets and TLS; they
    // carry no Git configuration. PATH is restricted to the Git installation's own dirs.
    if (process.platform === 'win32') {
      for (const name of ['SystemRoot', 'SYSTEMROOT', 'windir', 'ComSpec']) {
        const value = process.env[name];
        if (value) env[name] = value;
      }
    }
    const gitExecutable = options.gitExecutable ?? 'git';
    env['PATH'] = gitSearchPath(gitExecutable);
    return new SafeGit(
      scratch,
      gitDir,
      env,
      hardeningConfig(emptyDir, emptyFile, options.network),
      options.objectFormat,
      options.network,
      gitExecutable,
      options.defaultTimeoutMs ?? 60_000,
    );
  }

  async dispose(): Promise<void> {
    await rm(this.scratch, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }

  /** Run a fixed Git subcommand. `args` must never contain repository-derived options. */
  async run(
    args: readonly string[],
    options: { stdin?: Buffer | string; timeoutMs?: number; maxStdoutBytes?: number; signal?: AbortSignal; okExitCodes?: readonly number[] } = {},
  ): Promise<BoundedRunResult> {
    return runBounded(this.gitExecutable, [...this.hardening, ...args], {
      env: this.env,
      cwd: this.scratch,
      timeoutMs: options.timeoutMs ?? this.defaultTimeoutMs,
      maxStdoutBytes: options.maxStdoutBytes ?? 64 * 1024 * 1024,
      ...(options.stdin !== undefined ? { stdin: options.stdin } : {}),
      ...(options.signal ? { signal: options.signal } : {}),
      ...(options.okExitCodes ? { okExitCodes: options.okExitCodes } : {}),
    });
  }

  /**
   * Start a long-lived Git child (for request/response protocols such as
   * `cat-file --batch`) with the same hardening, environment and process-group ownership
   * as `run`. The caller owns the deadline and must call `killProcessTree` on failure.
   */
  spawnInteractive(args: readonly string[]): ChildProcessWithoutNullStreams {
    return spawn(this.gitExecutable, [...this.hardening, ...args], {
      cwd: this.scratch,
      env: { ...this.env },
      shell: false,
      windowsHide: true,
      detached: process.platform !== 'win32',
      stdio: ['pipe', 'pipe', 'pipe'],
    });
  }

  assertOid(oid: string): void {
    const length = this.objectFormat === 'sha256' ? 64 : 40;
    if (oid.length !== length || !/^[0-9a-f]+$/.test(oid)) {
      throw new IngestError('REF_INVALID', 'Expected a full object ID in the repository object format');
    }
  }
}

/** Directories that hold the trusted Git executable and its helpers. */
function gitSearchPath(gitExecutable: string): string {
  const fromPath = process.env['PATH'] ?? process.env['Path'] ?? '';
  if (path.isAbsolute(gitExecutable)) return path.dirname(gitExecutable);
  // Keep only entries that look like Git installations or system directories.
  const keep = fromPath
    .split(path.delimiter)
    .filter((dir) => /git|system32|\/usr\/bin|\/bin$|\/usr\/local\/bin|homebrew/i.test(dir));
  return keep.join(path.delimiter);
}

export async function gitVersion(gitExecutable = 'git'): Promise<string> {
  const git = await SafeGit.create({ gitExecutable, objectDirectory: null, objectFormat: 'sha1', network: { kind: 'offline' } });
  try {
    const result = await git.run(['version'], { timeoutMs: 10_000, maxStdoutBytes: 4096 });
    const match = /git version (\S+)/.exec(result.stdout.toString('utf8'));
    if (!match) throw new IngestError('GIT_UNAVAILABLE', 'Could not determine the Git version');
    return match[1]!;
  } finally {
    await git.dispose();
  }
}

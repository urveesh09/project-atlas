import { commitRawTree, createGitFixture, type GitFixture, type RawTreeEntry } from './git-fixture.js';

/**
 * Inventory fixture (task P1.2 / Gate G1). One commit whose tree is built directly with
 * `git mktree`, so it can hold entries no checkout could. Each entry declares its expected
 * outcome by hand, from plan §4.1/§4.3/§8.5 — not from running the analyzer.
 */
export type ExpectedOutcome =
  | { status: 'supported'; role: string; language: 'typescript' | 'javascript' }
  | { status: 'opaque'; role: string; reason: string | null }
  | { status: 'excluded'; reason: string };

export interface InventoryFixtureEntry {
  entry: RawTreeEntry;
  /** Display name for paths that are not valid UTF-8. */
  label?: string;
  expected: ExpectedOutcome;
}

const big = 'export const filler = 1;\n'.repeat(46_000); // ≈ 1.15 MB, over the 1 MiB cap
const lfsPointer = 'version https://git-lfs.github.com/spec/v1\noid sha256:4d7a214614ab2935c943f9e0ff69d22eadbb8f32b1258daaa5e2ca24d17e2393\nsize 12345\n';

export function inventoryFixtureEntries(submoduleTarget: string): InventoryFixtureEntry[] {
  const file = (path: string | Buffer, content: string | Buffer, expected: ExpectedOutcome, mode: RawTreeEntry['mode'] = '100644', label?: string): InventoryFixtureEntry => ({
    entry: { mode, path, content },
    expected,
    ...(label ? { label } : {}),
  });
  const ts = (role: string): ExpectedOutcome => ({ status: 'supported', role, language: 'typescript' });
  const js = (role: string): ExpectedOutcome => ({ status: 'supported', role, language: 'javascript' });
  return [
    // Supported TS/JS, by role.
    file('src/index.ts', 'export const a = 1;\n', ts('source')),
    file('src/util.js', 'module.exports = 1;\n', js('source')),
    file('src/App.tsx', 'export const App = () => null;\n', ts('source')),
    file('src/types.d.ts', 'export declare const x: number;\n', ts('declaration')),
    file('test/app.test.ts', "import { a } from '../src/index';\n", ts('test')),
    file('src/widget.spec.tsx', 'export {};\n', ts('test')),
    file('vite.config.ts', 'export default {};\n', ts('config')),
    file('build/output.js', 'export const notExcluded = true;\n', js('source')), // `build/` is deliberately not a built-in exclusion (ADR-017)
    file('deep/a/b/c/d/e/f.ts', 'export {};\n', ts('source')),
    file('BOM.ts', '﻿export const bom = 1;\n', ts('source')),
    // Configuration and structural files.
    file('package.json', '{ "name": "inventory-fixture", "private": true }\n', { status: 'opaque', role: 'config', reason: null }),
    file('tsconfig.json', '{ "compilerOptions": { "strict": true } }\n', { status: 'opaque', role: 'config', reason: null }),
    file('pnpm-lock.yaml', "lockfileVersion: '9.0'\n", { status: 'opaque', role: 'config', reason: 'LOCKFILE_STRUCTURAL' }),
    file('atlas.config.json', '{ "version": 1, "exclude": ["docs/generated/"] }\n', { status: 'opaque', role: 'config', reason: null }),
    // Non-code files stay visible as opaque buildings.
    file('README.md', '# fixture\n', { status: 'opaque', role: 'opaque', reason: null }),
    file('Readme.md', '# case-distinct twin\n', { status: 'opaque', role: 'opaque', reason: null }),
    file('assets/logo.png', Buffer.from([0x89, 0x50, 0x4e, 0x47, 0, 0, 0, 0]), { status: 'opaque', role: 'asset', reason: null }),
    file('src/styles.css', 'body {}\n', { status: 'opaque', role: 'asset', reason: null }),
    file('src/Comp.vue', '<template><div/></template>\n', { status: 'opaque', role: 'opaque', reason: 'LANGUAGE_UNSUPPORTED' }),
    // Code files that are kept but cannot be analyzed, each with a reason.
    file('src/flow.js', '// @flow\nexport const f = 1;\n', { status: 'opaque', role: 'source', reason: 'FLOW_UNSUPPORTED' }),
    file('src/latin1.ts', Buffer.from([0x63, 0x6f, 0x6e, 0x73, 0x74, 0x20, 0xe9, 0x3d, 0x31, 0x3b]), { status: 'opaque', role: 'source', reason: 'INVALID_ENCODING' }),
    file('src/binary.ts', Buffer.from([0x61, 0x00, 0x62, 0x00]), { status: 'opaque', role: 'source', reason: 'BINARY_CONTENT' }),
    file('src/huge.ts', big, { status: 'opaque', role: 'source', reason: 'OVERSIZE' }),
    file('assets/model.bin', lfsPointer, { status: 'opaque', role: 'opaque', reason: 'LFS_NOT_FETCHED' }),
    // Excluded by scope rules, never silently.
    file('node_modules/lib/index.js', 'module.exports = 1;\n', { status: 'excluded', reason: 'DEPENDENCY_DIRECTORY' }),
    file('packages/a/node_modules/x.js', 'module.exports = 1;\n', { status: 'excluded', reason: 'DEPENDENCY_DIRECTORY' }),
    file('dist/bundle.js', 'var a=1;\n', { status: 'excluded', reason: 'BUILD_OUTPUT' }),
    file('public/app.min.js', 'var a=1;\n', { status: 'excluded', reason: 'MINIFIED_BUNDLE' }),
    file('src/index.js.map', '{}\n', { status: 'excluded', reason: 'SOURCE_MAP' }),
    file('src/generated.ts', '// @generated by protoc. DO NOT EDIT.\nexport const g = 1;\n', { status: 'excluded', reason: 'GENERATED_HEADER' }),
    file('docs/generated/api.ts', 'export {};\n', { status: 'excluded', reason: 'REPOSITORY_EXCLUDED' }),
    file('link-to-etc', '/etc/passwd', { status: 'excluded', reason: 'SYMLINK' }, '120000'),
    file('vendor-sub', submoduleTarget, { status: 'excluded', reason: 'SUBMODULE' }, '160000'),
    file(Buffer.concat([Buffer.from('bad-'), Buffer.from([0xff, 0xfe]), Buffer.from('.ts')]), 'export {};\n', { status: 'excluded', reason: 'INVALID_UTF8_PATH' }, '100644', 'bad-<ff fe>.ts'),
    file('line\nbreak.ts', 'export {};\n', { status: 'excluded', reason: 'INVALID_PATH_CONTROL_CHARACTER' }, '100644', 'line\\nbreak.ts'),
  ];
}

export interface InventoryFixture {
  repo: GitFixture;
  head: string;
  entries: InventoryFixtureEntry[];
}

export function buildInventoryFixture(): InventoryFixture {
  const repo = createGitFixture([{ date: '2026-09-01T00:00:00Z', message: 'submodule target', files: { 'placeholder.txt': 'x' } }]);
  const entries = inventoryFixtureEntries(repo.commits[0]!);
  const head = commitRawTree(repo, entries.map((e) => e.entry), { date: '2026-09-02T00:00:00Z', message: 'inventory fixture', parent: repo.commits[0]! });
  repo.git(['update-ref', 'refs/heads/main', head]);
  return { repo, head, entries };
}
